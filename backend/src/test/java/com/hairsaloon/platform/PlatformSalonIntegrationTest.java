    @Test
    void publicDirectoryExcludesPendingAndSupportsEveryFilterAndStablePagination()
            throws Exception {
        long alpha = salon("alpha-owner@example.com", "alpha", "Alpha Salon",
            "Central", "ACTIVE");
        long beta = salon("beta-owner@example.com", "beta", "Beta Beauty",
            "West", "ACTIVE");
        salon("pending-owner@example.com", "pending", "Pending Salon", "Central", "PENDING");
        service(alpha, "Hair Cut", true);
        service(alpha, "Hidden Facial", false);
        service(beta, "Nail Art", true);
        review(alpha, 5);
        review(alpha, 4);
        review(beta, 3);

        mockMvc.perform(get("/api/platform/salons").header("Host", HOST))
            .andExpect(status().isOk())
            .andExpect(jsonPath("$.content.length()").value(2))
            .andExpect(jsonPath("$.content[0].subdomain").value("alpha"))
            .andExpect(jsonPath("$.content[0].rating").value(4.5))
            .andExpect(jsonPath("$.content[0].reviewCount").value(2))
            .andExpect(jsonPath("$.content[0].ownerId").doesNotExist())
            .andExpect(jsonPath("$.totalElements").value(2))
            .andExpect(jsonPath("$.page").value(0))
            .andExpect(jsonPath("$.size").value(20));

        mockMvc.perform(get("/api/platform/salons").header("Host", HOST)
                .param("city", " central "))
            .andExpect(status().isOk()).andExpect(jsonPath("$.totalElements").value(1));
        mockMvc.perform(get("/api/platform/salons").header("Host", HOST)
                .param("service", "hair"))
            .andExpect(status().isOk()).andExpect(jsonPath("$.totalElements").value(1));
        mockMvc.perform(get("/api/platform/salons").header("Host", HOST)
                .param("rating", "4.25"))
            .andExpect(status().isOk()).andExpect(jsonPath("$.totalElements").value(1));
        mockMvc.perform(get("/api/platform/salons").header("Host", HOST)
                .param("search", "alpha"))
            .andExpect(status().isOk()).andExpect(jsonPath("$.totalElements").value(1));

        mockMvc.perform(get("/api/platform/salons").header("Host", HOST)
                .param("city", " central ").param("service", "hair")
                .param("rating", "4.25").param("search", "alpha"))
            .andExpect(status().isOk())
            .andExpect(jsonPath("$.content.length()").value(1))
            .andExpect(jsonPath("$.content[0].subdomain").value("alpha"));

        mockMvc.perform(get("/api/platform/salons").header("Host", HOST)
                .param("service", "Hidden"))
            .andExpect(status().isOk())
            .andExpect(jsonPath("$.totalElements").value(0));

        mockMvc.perform(get("/api/platform/salons").header("Host", HOST)
                .param("page", "1").param("size", "1"))
            .andExpect(status().isOk())
            .andExpect(jsonPath("$.content[0].subdomain").value("beta"))
            .andExpect(jsonPath("$.totalElements").value(2))
            .andExpect(jsonPath("$.totalPages").value(2))
            .andExpect(jsonPath("$.first").value(false))
            .andExpect(jsonPath("$.last").value(true));

        mockMvc.perform(get("/api/platform/salons").header("Host", HOST)
                .param("page", "99").param("size", "1"))
            .andExpect(status().isOk())
            .andExpect(jsonPath("$.content.length()").value(0))
            .andExpect(jsonPath("$.totalElements").value(2))
            .andExpect(jsonPath("$.totalPages").value(2));

        mockMvc.perform(get("/api/platform/salons").header("Host", HOST)
                .param("size", "101"))
            .andExpect(status().isBadRequest())
            .andExpect(jsonPath("$.error").value("VALIDATION_ERROR"))
            .andExpect(jsonPath("$.fieldErrors.size").exists());
    }
    @Test
    void subdomainCheckNormalizesAndReportsAvailableReservedTakenAndInvalid() throws Exception {
        String owner = signup("checker@example.com", "SALON_OWNER");
        String customer = signup("customer@example.com", "CUSTOMER");
        salon("existing@example.com", "taken-name", "Taken", "Central", "PENDING");

        mockMvc.perform(get("/api/platform/salons/check-subdomain").header("Host", HOST)
                .cookie(cookie(owner)).param("name", "  Glamour-Studio  "))
            .andExpect(status().isOk())
            .andExpect(jsonPath("$.normalized").value("glamour-studio"))
            .andExpect(jsonPath("$.valid").value(true))
            .andExpect(jsonPath("$.available").value(true))
            .andExpect(jsonPath("$.reason").value("AVAILABLE"));

        mockMvc.perform(get("/api/platform/salons/check-subdomain").header("Host", HOST)
                .cookie(cookie(owner)).param("name", " API "))
            .andExpect(status().isOk())
            .andExpect(jsonPath("$.normalized").value("api"))
            .andExpect(jsonPath("$.valid").value(false))
            .andExpect(jsonPath("$.available").value(false))
            .andExpect(jsonPath("$.reason").value("RESERVED"));

        mockMvc.perform(get("/api/platform/salons/check-subdomain").header("Host", HOST)
                .cookie(cookie(owner)).param("name", "TAKEN-NAME"))
            .andExpect(status().isOk())
            .andExpect(jsonPath("$.normalized").value("taken-name"))
            .andExpect(jsonPath("$.available").value(false))
            .andExpect(jsonPath("$.reason").value("TAKEN"));

        mockMvc.perform(get("/api/platform/salons/check-subdomain").header("Host", HOST)
                .cookie(cookie(owner)).param("name", "-bad"))
            .andExpect(status().isBadRequest())
            .andExpect(jsonPath("$.error").value("VALIDATION_ERROR"))
            .andExpect(jsonPath("$.fieldErrors.name").exists());

        mockMvc.perform(get("/api/platform/salons/check-subdomain").header("Host", HOST))
            .andExpect(status().isUnauthorized());
        mockMvc.perform(get("/api/platform/salons/check-subdomain").header("Host", HOST)
                .cookie(cookie(customer)).param("name", "customer-name"))
            .andExpect(status().isForbidden());
    }

    @Test
    void ownerCreationDerivesOwnershipSanitizesResponseAndAllowsOnlyOneSalon()
            throws Exception {
        String owner = signup("real-owner@example.com", "SALON_OWNER");
        long ownerId = jdbc.queryForObject(
            "SELECT id FROM users WHERE email = 'real-owner@example.com'", Long.class);

        String injectedOwner = createJson("injected-studio", "Injected")
            .replaceFirst("\\{", "{\"ownerId\":999,");
        mockMvc.perform(post("/api/platform/salons").header("Host", HOST)
                .cookie(cookie(owner)).contentType(MediaType.APPLICATION_JSON)
                .content(injectedOwner))
            .andExpect(status().isBadRequest())
            .andExpect(jsonPath("$.error").value("BAD_REQUEST"));

        mockMvc.perform(post("/api/platform/salons").header("Host", HOST)
                .cookie(cookie(owner)).contentType(MediaType.APPLICATION_JSON)
                .content(createJson("  My-Studio  ", "  <b>My Salon</b>  ")))
            .andExpect(status().isCreated())
            .andExpect(jsonPath("$.subdomain").value("my-studio"))
            .andExpect(jsonPath("$.name").value("My Salon"))
            .andExpect(jsonPath("$.description").value("Friendly place"))
            .andExpect(jsonPath("$.email").value("salon@example.com"))
            .andExpect(jsonPath("$.status").value("PENDING"))
            .andExpect(jsonPath("$.ownerId").doesNotExist());

        assertThat(jdbc.queryForObject(
            "SELECT owner_id FROM salons WHERE subdomain = 'my-studio'", Long.class))
            .isEqualTo(ownerId);

        mockMvc.perform(post("/api/platform/salons").header("Host", HOST)
                .cookie(cookie(owner)).contentType(MediaType.APPLICATION_JSON)
                .content(createJson("second-studio", "Second")))
            .andExpect(status().isConflict())
            .andExpect(jsonPath("$.error").value("OWNER_SALON_EXISTS"));
    }
    @Test
    @WithMockUser(roles = "PLATFORM_ADMIN")
    void adminListsPendingApprovesItAndMakesItPublicAndTenantResolvable() throws Exception {
        long pendingId = salon("approval-owner@example.com", "approval", "Approval Salon",
            "Central", "PENDING");
        salon("active-owner@example.com", "other-active", "Other Active", "West", "ACTIVE");

        mockMvc.perform(get("/api/platform/admin/salons/pending").header("Host", HOST))
            .andExpect(status().isOk())
            .andExpect(jsonPath("$[0].id").value(pendingId))
            .andExpect(jsonPath("$[0].description").value("Fixture"))
            .andExpect(jsonPath("$[0].address").value("1 Main Street"))
            .andExpect(jsonPath("$[0].timezone").value("UTC"))
            .andExpect(jsonPath("$[0].ownerEmail").value("approval-owner@example.com"))
            .andExpect(jsonPath("$[0].status").value("PENDING"))
            .andExpect(jsonPath("$[1]").doesNotExist());

        mockMvc.perform(get("/api/platform/salons").header("Host", "approval.localhost"))
            .andExpect(status().isNotFound());

        mockMvc.perform(post("/api/platform/admin/salons/{id}/approve", pendingId)
                .header("Host", HOST))
            .andExpect(status().isOk())
            .andExpect(jsonPath("$.status").value("ACTIVE"));

        mockMvc.perform(get("/api/platform/salons").header("Host", HOST)
                .param("search", "Approval"))
            .andExpect(status().isOk())
            .andExpect(jsonPath("$.content[0].subdomain").value("approval"));
        mockMvc.perform(get("/api/platform/salons").header("Host", "approval.localhost"))
            .andExpect(status().isOk());

        mockMvc.perform(post("/api/platform/admin/salons/{id}/approve", pendingId)
                .header("Host", HOST))
            .andExpect(status().isConflict())
            .andExpect(jsonPath("$.error").value("INVALID_SALON_STATUS"));
        mockMvc.perform(post("/api/platform/admin/salons/{id}/approve", 999999)
                .header("Host", HOST))
            .andExpect(status().isNotFound())
            .andExpect(jsonPath("$.error").value("SALON_NOT_FOUND"));
    }

