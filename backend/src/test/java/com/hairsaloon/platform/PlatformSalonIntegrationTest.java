    @Test
    void creationRejectsReservedSubdomainInvalidLogoAndNonIanaTimezone() throws Exception {
        String owner = signup("validation-owner@example.com", "SALON_OWNER");
        mockMvc.perform(post("/api/platform/salons").header("Host", HOST)
                .cookie(cookie(owner)).contentType(MediaType.APPLICATION_JSON)
                .content(createJson("www", "Reserved")))
            .andExpect(status().isBadRequest())
            .andExpect(jsonPath("$.fieldErrors.subdomain").exists());

        mockMvc.perform(post("/api/platform/salons").header("Host", HOST)
                .cookie(cookie(owner)).contentType(MediaType.APPLICATION_JSON)
                .content(createJson("bad-logo", "Logo")
                    .replace("https://cdn.example.com/logo.png", "javascript:alert(1)")))
            .andExpect(status().isBadRequest())
            .andExpect(jsonPath("$.fieldErrors.logoUrl").exists());

        mockMvc.perform(post("/api/platform/salons").header("Host", HOST)
                .cookie(cookie(owner)).contentType(MediaType.APPLICATION_JSON)
                .content(createJson("bad-zone", "Zone")
                    .replace("America/New_York", "Mars/Olympus")))
            .andExpect(status().isBadRequest())
            .andExpect(jsonPath("$.fieldErrors.timezone").exists());
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM salons", Integer.class)).isZero();
    }

    private String signup(String email, String role) {
        return testUsers.create(email,
            com.hairsaloon.auth.UserRole.valueOf(role)).token();
    }

    private long salon(String ownerEmail, String subdomain, String name, String city,
                       String status) {
        testUsers.create(ownerEmail, com.hairsaloon.auth.UserRole.SALON_OWNER);
        long ownerId = jdbc.queryForObject("SELECT id FROM users WHERE email = ?",
            Long.class, ownerEmail);
        jdbc.update("""
            INSERT INTO salons
              (owner_id, subdomain, name, description, address, city, phone, email,
               logo_url, timezone, status, cancellation_window_minutes, created_at)
            VALUES (?, ?, ?, 'Fixture', '1 Main Street', ?, '+1 555 0100', ?,
                    'https://cdn.example.com/logo.png', 'UTC', ?, 120, CURRENT_TIMESTAMP)
            """, ownerId, subdomain, name, city, ownerEmail, status);
        return jdbc.queryForObject("SELECT id FROM salons WHERE subdomain = ?",
            Long.class, subdomain);
    }

    private void service(long salonId, String name, boolean active) {
        jdbc.update("INSERT INTO services (salon_id, name, duration_minutes, price, is_active, created_at) "
                + "VALUES (?, ?, 30, 25.00, ?, CURRENT_TIMESTAMP)",
            salonId, name, active);
    }

    private void review(long salonId, int rating) {
        jdbc.update("INSERT INTO reviews (salon_id, rating) VALUES (?, ?)", salonId, rating);
    }

    private static Cookie cookie(String token) {
        return new Cookie("auth_token", token);
    }

    private static String createJson(String subdomain, String name) {
        return """
            {
              "subdomain":"%s",
              "name":"%s",
              "description":"  <i>Friendly</i> place  ",
              "address":"  10 Main Street  ",
              "city":"  New York  ",
              "phone":" +1 (555) 010-2000 ",
              "email":" Salon@Example.COM ",
              "logoUrl":" https://cdn.example.com/logo.png ",
              "timezone":"America/New_York"
            }
            """.formatted(subdomain, name);
    }
