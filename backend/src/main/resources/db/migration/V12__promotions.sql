CREATE TABLE promotion_redemptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    salon_id BIGINT NOT NULL REFERENCES salons(id) ON DELETE CASCADE,
    promotion_id BIGINT NOT NULL,
    booking_id BIGINT NOT NULL,
    customer_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    status VARCHAR(16) NOT NULL DEFAULT 'RESERVED',
    discount_amount NUMERIC(12, 2) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    released_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT promotion_redemptions_promotion_fk FOREIGN KEY (promotion_id, salon_id)
        REFERENCES promotions(id, salon_id) ON DELETE RESTRICT,
    CONSTRAINT promotion_redemptions_booking_fk FOREIGN KEY (booking_id, salon_id)
        REFERENCES bookings(id, salon_id) ON DELETE CASCADE,
    CONSTRAINT promotion_redemptions_booking_unique UNIQUE (salon_id, booking_id),
    CONSTRAINT promotion_redemptions_status_check CHECK (status IN ('RESERVED', 'RELEASED')),
    CONSTRAINT promotion_redemptions_discount_check CHECK (discount_amount >= 0)
);

CREATE INDEX idx_promotions_salon_active_window
    ON promotions(salon_id, is_active, starts_at, ends_at);
CREATE INDEX idx_promotion_redemptions_limit
    ON promotion_redemptions(salon_id, promotion_id, status, customer_id);
